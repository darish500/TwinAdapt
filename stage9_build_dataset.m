%% stage9_build_dataset.m
% Runs every Stage 9 scenario (Section 28 A-H of the Stage 9 spec),
% concatenates the results, and exports the two dataset files.
%
% NOTE on PV/Battery degradation (Scenarios B, C): the model's degradation
% is a continuous function of simulated time, not a separate switch to
% flip -- so a single Healthy-baseline run ALREADY sweeps through the
% full aging trajectory across its own timeline (visible via Rs_aged and
% R0_aged in the exported metadata columns). Running a further batch of
% "degradation-only" scenarios would just be duplicating that same
% trajectory under a different label, so Scenarios B/C are represented
% by the Healthy_Baseline run alone rather than separate simulations.

clear all_rows;
allRows = {};

% ===== Scenario A: Healthy baseline (also sweeps PV+Battery degradation
% naturally across its own timeline -- see note above) =====
cfg = struct('Scenario_Name','Healthy_Baseline', ...
    'Asset_State','Healthy','Sensor_State','Healthy', ...
    'Environment_State','Nominal_G1000','Twin_State','Reference');
allRows{end+1} = stage9_run_scenario_v2(cfg);

% ===== Scenario D: PV asset faults, full severity =====
pvFaults = struct('code',{3,4,5,6}, 'name',{'Hotspot','PID','OpenCircuit','ShortCircuit'});
for i = 1:numel(pvFaults)
    cfg = struct('PV_FaultType',pvFaults(i).code, 'PV_FaultSeverity',1, ...
        'Scenario_Name',['PV_Fault_' pvFaults(i).name], ...
        'Asset_State',['PV_' pvFaults(i).name], 'Sensor_State','Healthy', ...
        'Environment_State','Nominal_G1000','Twin_State','Reference');
    allRows{end+1} = stage9_run_scenario_v2(cfg); %#ok<SAGROW>
end

% ===== Scenario E: Battery asset faults, full severity =====
battFaults = struct('code',{1,2,4,5}, 'name',{'CellImbalance','OverDischarge','ThermalRunaway','InternalShort'});
for i = 1:numel(battFaults)
    cfg = struct('Batt_FaultType',battFaults(i).code, 'Batt_FaultSeverity',1, ...
        'Scenario_Name',['Battery_Fault_' battFaults(i).name], ...
        'Asset_State',['Battery_' battFaults(i).name], 'Sensor_State','Healthy', ...
        'Environment_State','Nominal_G1000','Twin_State','Reference');
    allRows{end+1} = stage9_run_scenario_v2(cfg); %#ok<SAGROW>
end

% ===== Scenario F: Sensor faults, healthy asset (the mandatory case --
% proves sensor faults are distinguishable from asset faults) =====
cfg = struct('PV_SensorTarget',2, 'PV_SensorFaultType',1, 'PV_SensorFaultSeverity',1, ...
    'Scenario_Name','PV_SensorFault_VoltageBias', ...
    'Asset_State','Healthy', 'Sensor_State','PV_Voltage_Bias', ...
    'Environment_State','Nominal_G1000','Twin_State','Reference');
allRows{end+1} = stage9_run_scenario_v2(cfg);

cfg = struct('Batt_SensorTarget',0, 'Batt_SensorFaultType',1, 'Batt_SensorFaultSeverity',1, ...
    'Scenario_Name','Battery_SensorFault_VoltageBias', ...
    'Asset_State','Healthy', 'Sensor_State','Battery_Voltage_Bias', ...
    'Environment_State','Nominal_G1000','Twin_State','Reference');
allRows{end+1} = stage9_run_scenario_v2(cfg);

% ===== Scenario G: Environmental variation, healthy everything else =====
envLevels = [700, 1300];
for g = envLevels
    cfg = struct('G_test',g, ...
        'Scenario_Name',sprintf('Environmental_G%d',g), ...
        'Asset_State','Healthy', 'Sensor_State','Healthy', ...
        'Environment_State',sprintf('G%d',g), 'Twin_State','Reference');
    allRows{end+1} = stage9_run_scenario_v2(cfg); %#ok<SAGROW>
end

% ===== Scenario H: Twin parameter mismatch, healthy asset =====
cfg = struct('PV_Twin_Rs_Mult',1.05, ...
    'Scenario_Name','Twin_Mismatch_PV_Rs_plus5pct', ...
    'Asset_State','Healthy', 'Sensor_State','Healthy', ...
    'Environment_State','Nominal_G1000', 'Twin_State','PV_Rs_plus5pct');
allRows{end+1} = stage9_run_scenario_v2(cfg);

cfg = struct('Battery_Twin_R0_Mult',1.05, ...
    'Scenario_Name','Twin_Mismatch_Battery_R0_plus5pct', ...
    'Asset_State','Healthy', 'Sensor_State','Healthy', ...
    'Environment_State','Nominal_G1000', 'Twin_State','Battery_R0_plus5pct');
allRows{end+1} = stage9_run_scenario_v2(cfg);

%% Concatenate everything
FullDataset = vertcat(allRows{:});
save('Stage9_FeatureDataset.mat', 'FullDataset');
fprintf('Saved Stage9_FeatureDataset.mat with %d rows across %d scenarios.\n', ...
    height(FullDataset), numel(allRows));

%% Split into PV and Battery CSVs, deployment features and evaluation
% metadata kept as clearly separated column blocks within each (per
% Section 32) rather than mixed together.

pvDeployCols = {'t_grid','PV_Irradiance_Final','PV_Temperature_Final','PV_Voltage_Final','PV_Current_Final', ...
    'PV_Twin_Current','PV_Twin_Power','PV_Residual_Current','PV_Residual_Power', ...
    'PV_AbsResidual_Current','PV_AbsResidual_Power', ...
    'PV_Normalized_Current_Residual','PV_Normalized_Power_Residual', ...
    'PV_Residual_Current_Mean','PV_Residual_Current_Std','PV_Residual_Current_MaxAbs', ...
    'PV_Residual_Power_Mean','PV_Residual_Power_Std','PV_Residual_Power_MaxAbs', ...
    'PV_Residual_Current_Trend','PV_Residual_Power_Trend', ...
    'PV_Valid_Operating_Condition','PV_Feature_Window_Valid','PV_Trend_Window_Valid','PV_Twin_Valid_Operating_Point'};

pvMetaCols = {'True_PV_Irradiance','True_PV_Temperature','True_PV_Voltage','True_PV_Current','Rs_aged', ...
    'Fault_Type','Fault_Severity','Fault_Active', ...
    'PV_SensorFault_Type','PV_SensorFault_Severity','PV_SensorFault_Active', ...
    'Scenario_Name','Asset_State','Sensor_State','Environment_State','Twin_State'};

battDeployCols = {'t_grid','Battery_Voltage_Final','Battery_Current_Final','Battery_Temperature_Final', ...
    'Battery_Twin_Voltage','Battery_Twin_SOC_Estimate', ...
    'Battery_Residual_Voltage','Battery_AbsResidual_Voltage','Battery_Normalized_Voltage_Residual', ...
    'Battery_Residual_Voltage_Mean','Battery_Residual_Voltage_Std','Battery_Residual_Voltage_MaxAbs','Battery_Residual_Voltage_Trend', ...
    'Battery_Feature_Window_Valid','Battery_Trend_Window_Valid'};

battMetaCols = {'True_Battery_Voltage','True_Battery_Current','True_Battery_Temperature','R0_aged', ...
    'Battery_Fault_Type','Battery_Fault_Severity','Battery_Fault_Active', ...
    'Battery_SensorFault_Type','Battery_SensorFault_Severity','Battery_SensorFault_Active', ...
    'Scenario_Name','Asset_State','Sensor_State','Environment_State','Twin_State'};

PV_Table = FullDataset(:, [pvDeployCols, pvMetaCols]);
Battery_Table = FullDataset(:, [battDeployCols, battMetaCols]);

writetable(PV_Table, 'Stage9_PV_Features.csv');
writetable(Battery_Table, 'Stage9_Battery_Features.csv');

fprintf('Exported Stage9_PV_Features.csv (%d rows, %d cols: %d deployment + %d metadata)\n', ...
    height(PV_Table), width(PV_Table), numel(pvDeployCols), numel(pvMetaCols));
fprintf('Exported Stage9_Battery_Features.csv (%d rows, %d cols: %d deployment + %d metadata)\n', ...
    height(Battery_Table), width(Battery_Table), numel(battDeployCols), numel(battMetaCols));